def report_path(stem: str, lang: Lang, *, directory: str | None = None) -> str:
    """Return ``summary.de.md``-style filename (optionally under a directory)."""
    name = f"{stem}.{lang}.md"
    return f"{directory.rstrip('/')}/{name}" if directory else name
